// Anchor reference: 1970-01-01 BS = 1913-04-13 AD (Sunday)
const ANCHOR_BS_YEAR = 1970;
const ANCHOR_AD_DATE = new Date(1913, 3, 13); // Apr 13, 1913

// Get total days in a given BS month
export function getBsMonthLength(year: number, month: number): number {
  const monthIdx = month - 1;
  const yearData = BS_FULL_CALENDAR_MAP[year];
  if (yearData && yearData[monthIdx]) {
    return yearData[monthIdx];
  }
  const defaultDist = [31, 31, 32, 31, 31, 30, 30, 29, 30, 29, 30, 30];
  return defaultDist[monthIdx] || 30;
}

// Convert BS Date to JS Date
export function rawBsToJsDate(bsYear: number, bsMonth: number, bsDay: number): Date {
  let totalDays = 0;

  if (bsYear >= ANCHOR_BS_YEAR) {
    for (let y = ANCHOR_BS_YEAR; y < bsYear; y++) {
      const yDays = BS_FULL_CALENDAR_MAP[y] || [31, 31, 32, 31, 31, 30, 30, 29, 30, 29, 30, 30];
      for (const mDays of yDays) {
        totalDays += mDays;
      }
    }
    const currentYearDays = BS_FULL_CALENDAR_MAP[bsYear] || [31, 31, 32, 31, 31, 30, 30, 29, 30, 29, 30, 30];
    for (let m = 0; m < bsMonth - 1; m++) {
      totalDays += currentYearDays[m];
    }
    totalDays += bsDay - 1;

    const resultTime = ANCHOR_AD_DATE.getTime() + totalDays * 24 * 60 * 60 * 1000;
    return new Date(resultTime);
  } else {
    // Before anchor
    for (let y = bsYear; y < ANCHOR_BS_YEAR; y++) {
      const yDays = BS_FULL_CALENDAR_MAP[y] || [31, 31, 32, 31, 31, 30, 30, 29, 30, 29, 30, 30];
      for (const mDays of yDays) {
        totalDays += mDays;
      }
    }
    const currentYearDays = BS_FULL_CALENDAR_MAP[bsYear] || [31, 31, 32, 31, 31, 30, 30, 29, 30, 29, 30, 30];
    for (let m = 0; m < bsMonth - 1; m++) {
      totalDays -= currentYearDays[m];
    }
    totalDays -= bsDay - 1;

    const resultTime = ANCHOR_AD_DATE.getTime() - totalDays * 24 * 60 * 60 * 1000;
    return new Date(resultTime);
  }
}

// Convert JS Date to BS Date
export function rawJsDateToBs(date: Date): { year: number; month: number; day: number } {
  const diffTime = date.getTime() - ANCHOR_AD_DATE.getTime();
  let remainingDays = Math.floor(diffTime / (24 * 60 * 60 * 1000));

  if (remainingDays < 0) {
    return { year: 1970, month: 1, day: 1 };
  }

  let curYear = ANCHOR_BS_YEAR;

  while (curYear <= BS_YEARS_MAX) {
    const yDays = BS_FULL_CALENDAR_MAP[curYear] || [31, 31, 32, 31, 31, 30, 30, 29, 30, 29, 30, 30];
    const totalDaysInYear = yDays.reduce((a, b) => a + b, 0);

    if (remainingDays < totalDaysInYear) {
      for (let m = 0; m < 12; m++) {
        const mDays = yDays[m];
        if (remainingDays < mDays) {
          return {
            year: curYear,
            month: m + 1,
            day: remainingDays + 1,
          };
        }
        remainingDays -= mDays;
      }
    }

    remainingDays -= totalDaysInYear;
    curYear++;
  }

  return { year: BS_YEARS_MAX, month: 12, day: 30 };
}
