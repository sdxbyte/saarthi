export interface ReceiptPDFData {
  merchantName: string;
  date: string;
  totalAmount: number;
  taxAmount: number;
  category: string;
  items?: { name: string; price: number }[];
  summaryNotes?: string;
}

export function generateReceiptPDF(data: ReceiptPDFData): void {
  const doc = new jsPDF();

  // Header banner
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, 210, 40, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.text('SAARTHI CIVIC DIGITAL PLATFORM', 14, 18);

  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(226, 232, 240);
  doc.text('Scanned Expense & Purchase Receipt Statement', 14, 28);

  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.text(`Generated Date: ${new Date().toLocaleString()}`, 14, 35);

  // Statement Box
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(14, 48, 182, 52, 3, 3, 'FD');

  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(15, 23, 42);
  doc.text(data.merchantName || 'Merchant Expense Receipt', 20, 58);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text(`Transaction Date: ${data.date || 'N/A'}`, 20, 68);
  doc.text(`Expense Category: ${data.category || 'General'}`, 20, 76);
  if (data.summaryNotes) {
    doc.text(`Notes: ${data.summaryNotes}`, 20, 84);
  }

  doc.setFont('helvetica', 'bold');
  doc.setTextColor(16, 185, 129);
  doc.text(`Total Amount Paid: Rs. ${data.totalAmount ? data.totalAmount.toLocaleString() : '0'}`, 110, 68);
  doc.setTextColor(217, 119, 6);
  doc.text(`VAT / Tax Included: Rs. ${data.taxAmount ? data.taxAmount.toLocaleString() : '0'}`, 110, 76);

  // Itemized breakdown if available
  let finalY = 112;
  if (data.items && data.items.length > 0) {
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(15, 23, 42);
    doc.text('Itemized Purchased Goods & Services', 14, 112);

    let startY = 118;
    doc.setFillColor(30, 41, 59);
    doc.rect(14, startY, 182, 8, 'F');

    doc.setFontSize(9);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(255, 255, 255);
    doc.text('Item Description', 18, startY + 6);
    doc.text('Price (NPR)', 160, startY + 6);

    startY += 8;
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(51, 65, 85);

    data.items.forEach((item, index) => {
      const rowY = startY + index * 8;
      if (index % 2 === 0) {
        doc.setFillColor(241, 245, 249);
        doc.rect(14, rowY, 182, 8, 'F');
      }
      doc.text(item.name, 18, rowY + 5.5);
      doc.text(`Rs. ${item.price.toLocaleString()}`, 160, rowY + 5.5);
    });

    finalY = startY + data.items.length * 8 + 15;
  }

  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text('Note: Digitally processed expense receipt statement from SAARTHI Digital Receipt Engine.', 14, finalY);

  doc.save(`SAARTHI_Receipt_${(data.merchantName || 'Expense').replace(/[^a-zA-Z0-9]/g, '_')}.pdf`);
}
